/* ---------------- escaping helpers ---------------- */

function escapeHtml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function escapeAttr(s) {
  return escapeHtml(s).replace(/"/g, '&quot;');
}
function escapeXml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
/* strip anything that could close the JSON-LD script element */
function escapeJsonLd(s) {
  return JSON.stringify(s).replace(/<\//g, '<\\/');
}
function safeUrl(u) {
  const t = String(u).trim();
  if (/^javascript:/i.test(t)) return false;
  return /^(https?:|mailto:|#|\/|\.{1,2}\/|[a-z0-9._~-])/i.test(t);
}

/* ---------------- front matter ---------------- */

function parseFrontMatter(raw, file) {
  const src = raw.replace(/\r\n?/g, '\n');
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) throw new Error(`${file}: missing front matter (--- block at the top of the file)`);
  const data = {};
  for (const line of m[1].split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const kv = line.match(/^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/);
    if (!kv) throw new Error(`${file}: bad front matter line: "${line}"`);
    data[kv[1].toLowerCase()] = kv[2].trim();
  }
  return { data, body: src.slice(m[0].length) };
}

function slugifyHeading(text, seen) {
  let id = text.toLowerCase()
    .replace(/`|\*|_/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'section';
  if (seen.has(id)) {
    const n = seen.get(id) + 1;
    seen.set(id, n);
    id = `${id}-${n}`;
  } else {
    seen.set(id, 0);
  }
  return id;
}

/* ---------------- inline markdown ---------------- */

function inline(text) {
  const store = [];
  const tok = (html) => `\x00${store.push(html) - 1}\x00`;
  let s = String(text);

  s = s.replace(/\\([\\`*_{}[\]()#+\-.!|~])/g, (_, c) => tok(escapeHtml(c)));       // backslash escapes
  s = s.replace(/`([^`\n]+)`/g, (_, c) => tok(`<code>${escapeHtml(c)}</code>`));    // code spans
  s = escapeHtml(s);                                                               // escape the rest

  s = s.replace(/!\[([^\]]*)\]\(([^)\s]+)\)/g, (orig, alt, src) =>
    safeUrl(src) ? `<img src="${escapeAttr(src)}" alt="${escapeAttr(alt)}" loading="lazy">` : orig);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (orig, txt, url) =>
    safeUrl(url) ? `<a href="${escapeAttr(url)}">${txt}</a>` : orig);
  s = s.replace(/&lt;(https?:\/\/[^\s&]+)&gt;/g, '<a href="$1">$1</a>');            // autolinks

  s = s.replace(/\*\*(?=\S)([^]+?)(?<=\S)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/(?<![\w*])\*(?!\s)([^*]+?)(?<!\s)\*(?!\w)/g, '<em>$1</em>');
  s = s.replace(/(?<![\w_])_(?!\s)([^_]+?)(?<!\s)_(?!\w)/g, '<em>$1</em>');
  s = s.replace(/~~(?=\S)(.+?)(?<=\S)~~/g, '<del>$1</del>');

  return s.replace(/\x00(\d+)\x00/g, (_, n) => store[Number(n)]);
}

/* ---------------- block markdown ---------------- */

function isBlockStart(lines, i) {
  const line = lines[i];
  return /^\s*$/.test(line)
    || /^```/.test(line)
    || /^#{1,6}\s/.test(line)
    || /^\s*([-*_])(\s*\1){2,}\s*$/.test(line)
    || /^\s*>/.test(line)
    || /^(\s*)([-*+]|\d{1,9}[.)])\s+/.test(line);
}

function splitTableRow(s) {
  let t = s.trim();
  if (t.startsWith('|')) t = t.slice(1);
  if (t.endsWith('|')) t = t.slice(0, -1);
  return t.split(/(?<!\\)\|/).map((c) => c.replace(/\\\|/g, '|'));
}

function renderBlocks(lines, headingSeen) {
  const out = [];
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];

    if (/^\s*$/.test(line)) { i++; continue; }

    // fenced code block
    let m = line.match(/^```([\w+-]*)\s*$/);
    if (m) {
      const lang = m[1];
      const buf = [];
      i++;
      while (i < lines.length && !/^```\s*$/.test(lines[i])) { buf.push(lines[i]); i++; }
      if (i < lines.length) i++; // skip closing fence
      const cls = lang ? ` class="language-${lang}"` : '';
      out.push(`<pre><code${cls}>${escapeHtml(buf.join('\n'))}\n</code></pre>`);
      continue;
    }

    // heading
    m = line.match(/^(#{1,6})\s+(.*)$/);
    if (m) {
      const level = m[1].length;
      const text = m[2].trim();
      const id = slugifyHeading(text, headingSeen);
      out.push(`<h${level} id="${id}">${inline(text)}</h${level}>`);
      i++;
      continue;
    }

    // horizontal rule
    if (/^\s*([-*_])(\s*\1){2,}\s*$/.test(line)) { out.push('<hr>'); i++; continue; }

    // blockquote
    if (/^\s*>/.test(line)) {
      const buf = [];
      while (i < lines.length && /^\s*>/.test(lines[i])) {
        buf.push(lines[i].replace(/^\s*>\s?/, ''));
        i++;
      }
      out.push(`<blockquote>${renderBlocks(buf, headingSeen)}</blockquote>`);
      continue;
    }

    // table: header row + |---| separator
    if (line.includes('|') && i + 1 < lines.length
        && /^\s*\|?[\s:|-]*-[\s:|-]*\|?[\s:|-]*$/.test(lines[i + 1])) {
      const header = splitTableRow(line);
      const sep = splitTableRow(lines[i + 1]);
      if (header.length === sep.length && header.length > 1 && sep.every((c) => /^:?-+:?$/.test(c.trim()))) {
        const aligns = sep.map((c) => {
          const t = c.trim();
          return (t.startsWith(':') && t.endsWith(':')) ? 'center' : t.endsWith(':') ? 'right' : '';
        });
        i += 2;
        const rows = [];
        while (i < lines.length && lines[i].includes('|') && !/^\s*$/.test(lines[i])) {
          rows.push(splitTableRow(lines[i]));
          i++;
        }
        const cell = (tag, txt, k) =>
          `<${tag}${aligns[k] ? ` style="text-align:${aligns[k]}"` : ''}>${inline(String(txt).trim())}</${tag}>`;
        const thead = `<tr>${header.map((c, k) => cell('th', c, k)).join('')}</tr>`;
        const tbody = rows.map((r) => `<tr>${header.map((_, k) => cell('td', r[k] || '', k)).join('')}</tr>`).join('');
        out.push(`<div class="tablewrap"><table><thead>${thead}</thead><tbody>${tbody}</tbody></table></div>`);
        continue;
      }
    }

    // lists
    m = line.match(/^(\s*)([-*+]|\d{1,9}[.)])\s+/);
    if (m) {
      const indent = m[1].length;
      const ordered = /\d/.test(m[2]);
      const markerRe = ordered ? /^(\s*)(\d{1,9}[.)])\s+/ : /^(\s*)([-*+])\s+/;
      const items = [];
      let cur = null;
      while (i < lines.length) {
        const mm = lines[i].match(markerRe);
        if (mm && mm[1].length === indent) {
          if (cur) items.push(cur);
          cur = [lines[i].slice(mm[0].length)];
          i++;
        } else if (cur !== null && !/^\s*$/.test(lines[i]) && !isBlockStart(lines, i)) {
          // continuation: indented lines are dedented, plain lines are lazy continuations
          const l = lines[i];
          cur.push(/^\s{2,}/.test(l) ? l.slice(Math.min(indent + 2, l.length)) : l.trim());
          i++;
        } else break;
      }
      if (cur) items.push(cur);
      const html = items.map((it) => {
        let inner = renderBlocks(it, headingSeen).trim();
        const oneP = inner.match(/^<p>([\s\S]*)<\/p>$/);
        if (oneP && !oneP[1].includes('<p>')) inner = oneP[1]; // unwrap single-paragraph items
        return `<li>${inner}</li>`;
      }).join('');
      out.push(ordered ? `<ol>${html}</ol>` : `<ul>${html}</ul>`);
      continue;
    }

    // paragraph
    const buf = [];
    while (i < lines.length && !isBlockStart(lines, i)) { buf.push(lines[i].trim()); i++; }
    if (buf.length) out.push(`<p>${inline(buf.join(' '))}</p>`);
    else i++;
  }

  return out.join('\n');
}

function renderMarkdown(src) {
  return renderBlocks(src.replace(/\r\n?/g, '\n').split('\n'), new Map());
}

