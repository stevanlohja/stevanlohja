/* ---------------- build ---------------- */

function readPosts() {
  if (!existsSync(BLOG)) mkdirSync(BLOG, { recursive: true });
  const files = readdirSync(BLOG).filter((f) => f.endsWith('.md') && !f.startsWith('_') && !f.startsWith('.'));
  const posts = [];
  const slugs = new Set();

  for (const file of files) {
    const slug = file.slice(0, -3);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) {
      throw new Error(`blog/${file}: filename must be lowercase letters, digits and dashes (it becomes the URL)`);
    }
    if (slug === 'index') throw new Error('blog/index.md: "index" is reserved for the generated listing page');
    if (slugs.has(slug)) throw new Error(`duplicate slug: ${slug}`);
    slugs.add(slug);

    const { data, body } = parseFrontMatter(readFileSync(join(BLOG, file), 'utf8'), `blog/${file}`);

    if (!data.title) throw new Error(`blog/${file}: front matter needs "title"`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date || '')) {
      throw new Error(`blog/${file}: front matter needs "date" as YYYY-MM-DD`);
    }
    if (Number.isNaN(new Date(`${data.date}T12:00:00Z`).getTime())) {
      throw new Error(`blog/${file}: "date" is not a valid date`);
    }
    const draft = /^(true|yes|1)$/i.test(data.draft || '');
    const tags = (data.tags || '').split(',').map((t) => t.trim()).filter(Boolean);
    const summary = data.summary || '';

    posts.push({
      slug, file, draft,
      title: data.title,
      date: data.date,
      summary,
      tags,
      html: renderMarkdown(body),
    });
  }

  posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug < b.slug ? -1 : 1));
  return posts;
}

